package postgresio

import (
	"strconv"
	"strings"
)

// formatVectorLiteral renders a float32 slice in pgvector's text literal
// syntax, "[1.5,-2,3.25]". The sink writes []float32 fields this way so they
// can be bound to a vector column.
func formatVectorLiteral(vec []float32) string {
	if len(vec) == 0 {
		return "[]"
	}
	var sb strings.Builder
	sb.WriteByte('[')
	for i, v := range vec {
		if i > 0 {
			sb.WriteByte(',')
		}
		sb.WriteString(strconv.FormatFloat(float64(v), 'f', -1, 32))
	}
	sb.WriteByte(']')
	return sb.String()
}
